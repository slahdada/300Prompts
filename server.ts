import express from 'express';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function startServer() {
  const app = express();
  const PORT = parseInt(process.env.PORT || '3000', 10);

  app.use(express.json({ limit: '10mb' }));

  // Helper to create GoogleGenAI instance with API key and user agent
  const getAiClient = () => {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      throw new Error('GEMINI_API_KEY is not configured in the environment.');
    }
    return new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    });
  };

  // API Route: Generate representative illustration for a prompt
  app.post('/api/generate-illustration', async (req, res) => {
    try {
      const { title, promptText, category, slash } = req.body;

      if (!title && !promptText && !slash) {
        return res.status(400).json({ error: 'Subject information is required.' });
      }

      const ai = getAiClient();
      const subject = title || slash || 'Artificial Intelligence';
      const cleanSnippet = (promptText || '').slice(0, 200).replace(/[\[\]]/g, ' ');

      // Detailed prompt according to image generation guidelines
      const visualPrompt = `A high-end 3D digital concept art illustration visualizing the concept of "${subject}". Category: ${category || 'Technology'}. Theme details: ${cleanSnippet}. Style: Sleek modern isometric 3D render, dark futuristic background, vibrant glowing accents of electric indigo, cyan and violet, volumetric lighting, photorealistic textures, clean composition, centered, 8k resolution feel, professional tech aesthetic, absolutely no text, no letters, no words.`;

      const response = await ai.models.generateContent({
        model: 'gemini-3.1-flash-lite-image',
        contents: {
          parts: [{ text: visualPrompt }]
        },
        config: {
          imageConfig: {
            aspectRatio: '1:1'
          }
        }
      });

      let imageUrl: string | null = null;
      for (const part of response.candidates?.[0]?.content?.parts ?? []) {
        if (part.inlineData?.data) {
          const mime = part.inlineData.mimeType ?? 'image/png';
          imageUrl = `data:${mime};base64,${part.inlineData.data}`;
          break;
        }
      }

      if (!imageUrl) {
        return res.status(500).json({
          error: 'No image data was generated by the model. Please try again.'
        });
      }

      return res.json({
        success: true,
        imageUrl,
        prompt: visualPrompt
      });
    } catch (err: any) {
      console.error('Error generating illustration:', err);
      return res.status(500).json({
        error: err.message || 'Failed to generate illustration'
      });
    }
  });

  // Vite development middleware or production static files
  if (process.env.NODE_ENV !== 'production') {
    const { createServer } = await import('vite');
    const vite = await createServer({
      server: {
        middlewareMode: true,
        hmr: process.env.DISABLE_HMR !== 'true',
        watch: process.env.DISABLE_HMR === 'true' ? null : {}
      }
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.join(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.join(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Prompt Master Library full-stack server running on port ${PORT}`);
  });
}

startServer().catch(err => {
  console.error('Fatal server startup error:', err);
  process.exit(1);
});
